// Identifies a workbook this platform generated.
//
// Every bill / budget workbook ADLM produces is a REPORT, not an import source.
// Feeding one back into the Excel importer would create a second project
// holding a copy of a bill the account already has — burning a project slot and
// leaving two records of the same job that drift apart the moment either is
// edited. So exports are stamped here and the importer refuses them, pointing
// the user back at the model the quantities actually came from.
//
// The stamp lives in two places on purpose:
//   • the workbook's document properties (keywords / category), which Excel,
//     LibreOffice and Sheets all preserve through a normal save; and
//   • a visible line on the Cover sheet, which survives even a
//     copy-everything-into-a-new-workbook, as long as the cover comes along.
// Either one is enough to recognise the file.

export const ADLM_EXPORT_MARKER = "adlm-export";

// Older Bill & Budget workbooks carried this marker before the stamp was
// generalised across every exporter. Still recognised so files already in
// users' hands are rejected too.
const LEGACY_MARKERS = ["adlm-bill-budget"];

const ALL_MARKERS = [ADLM_EXPORT_MARKER, ...LEGACY_MARKERS];

/** The visible line written at the foot of an export's cover sheet. */
export const ADLM_EXPORT_COVER_NOTE =
  `Generated by ADLM Studio (${ADLM_EXPORT_MARKER}) — this workbook is a report, not an import file.`;

/** Stamp an ExcelJS workbook as an ADLM export. */
export function stampAdlmWorkbook(workbook, { creator = "ADLM Studio" } = {}) {
  if (!workbook) return workbook;
  workbook.creator = creator;
  workbook.keywords = ADLM_EXPORT_MARKER;
  workbook.category = ADLM_EXPORT_MARKER;
  return workbook;
}

function hasMarker(value) {
  const s = String(value || "").toLowerCase();
  return ALL_MARKERS.some((m) => s.includes(m));
}

/** True when the loaded ExcelJS workbook is one of our own exports. */
export function isAdlmWorkbook(workbook) {
  if (!workbook) return false;

  const meta = [
    workbook.keywords,
    workbook.category,
    workbook.subject,
    workbook.description,
    workbook.company,
  ].join(" ");
  if (hasMarker(meta)) return true;

  // Fallback: the visible cover note. Only the cover is scanned, and only its
  // first few rows of text, so this cannot be tripped by a bill line that
  // happens to mention ADLM.
  for (const ws of workbook.worksheets || []) {
    if (!/^cover$/i.test(String(ws.name || "").trim())) continue;
    let found = false;
    ws.eachRow({ includeEmpty: false }, (row) => {
      if (found) return;
      row.eachCell({ includeEmpty: false }, (cell) => {
        if (found) return;
        const v = cell.value;
        const text =
          typeof v === "string"
            ? v
            : v && typeof v === "object" && Array.isArray(v.richText)
              ? v.richText.map((r) => r?.text || "").join("")
              : "";
        if (hasMarker(text)) found = true;
      });
    });
    if (found) return true;
  }

  return false;
}
